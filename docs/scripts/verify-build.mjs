#!/usr/bin/env node
// Checks the built site after `docusaurus build`. A build can succeed and still
// produce inconsistent output (for example pages at new URLs while the
// browser-side site data still lists old ones), so deployment checks the
// result, not just the exit code.
//
// Usage (from docs/): node scripts/verify-build.mjs
// Uses DOCS_BASE_URL, the same as the build (default "/").

import fs from 'node:fs';
import path from 'node:path';

const siteDir = path.resolve(import.meta.dirname, '..');
const buildDir = path.join(siteDir, 'build');
const baseUrl = process.env.DOCS_BASE_URL ?? '/';

// Pages that must always exist (paths without the base URL).
const requiredPages = ['/', '/about', '/about/features', '/frameworks', '/hybrid', '/plugins'];

const problems = [];
const fail = (message) => problems.push(message);

function stripBase(route) {
  return baseUrl !== '/' && route.startsWith(baseUrl) ? `/${route.slice(baseUrl.length)}` : route;
}

// Built file for a route, honoring trailingSlash: false (/about -> about.html).
function pageFile(route) {
  const clean = stripBase(route).replace(/\/$/, '');
  return clean === ''
    ? path.join(buildDir, 'index.html')
    : [path.join(buildDir, `${clean}.html`), path.join(buildDir, clean, 'index.html')].find((f) =>
        fs.existsSync(f),
      );
}

function readPage(route) {
  const file = pageFile(route);
  return file && fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : undefined;
}

// The navbar's right side, where the package version picker renders.
function navbarRight(html) {
  const start = html.indexOf('navbar__items--right');
  return start < 0 ? '' : html.slice(start, start + 2000);
}

if (!fs.existsSync(buildDir)) {
  console.error(`No build output at ${buildDir}; run the build first.`);
  process.exit(1);
}

for (const route of requiredPages) {
  if (!readPage(route)) fail(`missing page ${route}`);
}

// Browser-side site data generated by this build.
const globalDataFile = path.join(siteDir, '.docusaurus', 'globalData.json');
if (!fs.existsSync(globalDataFile)) {
  fail('missing .docusaurus/globalData.json');
} else {
  const globalData = JSON.parse(fs.readFileSync(globalDataFile, 'utf8'));
  const docsPlugins = globalData['docusaurus-plugin-content-docs'] ?? {};
  const packages = Object.entries(docsPlugins).filter(([id]) => id !== 'default');
  if (packages.length === 0) fail('site data lists no package docs');

  for (const [id, plugin] of packages) {
    for (const version of plugin.versions) {
      // Every version the browser knows about must have a built landing page,
      // whose version picker shows that version's label.
      const html = readPage(version.path);
      if (!html) {
        fail(`${id} ${version.label}: site data lists ${version.path}, but no page was built there`);
        continue;
      }
      if (!navbarRight(html).includes(`>${version.label}<`)) {
        fail(`${id} ${version.label}: version picker missing on ${stripBase(version.path)}`);
      }
      // The API reference must exist for each version.
      if (!readPage(`${version.path}/api`)) {
        fail(`${id} ${version.label}: missing API reference at ${stripBase(version.path)}/api`);
      }
    }

    // One search index per package search context, plus the site-wide one.
    const context = stripBase(plugin.path).replace(/^\//, '').replace(/\//g, '-');
    if (!fs.existsSync(path.join(buildDir, `search-index-${context}.json`))) {
      fail(`${id}: missing search index search-index-${context}.json`);
    }
  }
}
if (!fs.existsSync(path.join(buildDir, 'search-index.json'))) fail('missing search-index.json');

if (problems.length) {
  console.error(`Built site check failed:\n${problems.map((p) => `  - ${p}`).join('\n')}`);
  process.exit(1);
}
console.log('Built site check passed.');
