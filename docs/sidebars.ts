import type { SidebarsConfig } from '@docusaurus/plugin-content-docs';

// Docusaurus's own sidebar item type (one entry of a sidebar's item list).
type SidebarItem = Extract<SidebarsConfig[string], unknown[]>[number];
type GeneratedCategory = { label: string; items: SidebarItem[] };

// TypeDoc writes one sidebar per package, grouped by the @category tags in the
// source. Untagged symbols land in "Unlisted" (each package's typedoc.json
// defaultCategory): their pages are still built and linkable, just not listed.
function typedocCategories(pkg: string): Record<string, SidebarItem[]> {
  const generated: GeneratedCategory[] = require(`./docs/api/${pkg}/typedoc-sidebar.cjs`);
  return Object.fromEntries(generated.map((c) => [c.label, c.items]));
}

function page(pkg: string, path: string, label: string): SidebarItem {
  return { type: 'doc', id: `api/${pkg}/${path}`, label };
}

function category(label: string, items: SidebarItem[]): SidebarItem {
  return { type: 'category', label, items };
}

const core = typedocCategories('core');
const angular = typedocCategories('angular');

const sidebars: SidebarsConfig = {
  getStarted: [{ type: 'autogenerated', dirName: 'get-started' }],
  api: [
    // Landing page (docs/api.mdx) listing every package.
    { type: 'doc', id: 'api', label: 'Overview' },
    {
      type: 'category',
      label: '@uirouter/core',
      link: { type: 'doc', id: 'api/core/index' },
      items: [
        // The router entry point, listed on its own above the categories.
        page('core', 'classes/UIRouter', 'UIRouter'),
        ...Object.entries(core)
          .filter(([label]) => label !== 'Unlisted')
          .map(([label, items]) => category(label, items)),
      ],
    },
    {
      type: 'category',
      label: '@uirouter/angular',
      link: { type: 'doc', id: 'api/angular/index' },
      // Angular re-exports Core, and Core's tags come along with it. Angular's
      // own symbols are tagged in its source; the Core symbols this menu needs
      // are picked here.
      items: [
        category('UIRouter', [
          page('angular', 'classes/UIRouter', 'UIRouter'),
          ...angular['UIRouter'],
        ]),
        category(
          'Services',
          angular['Services'].filter(
            (item) =>
              !(typeof item === 'object' && 'id' in item && item.id === 'api/angular/classes/ViewService'),
          ),
        ),
        category('Components', angular['Components']),
        category('Standalone', angular['Standalone']),
        category('Other', [
          page('angular', 'classes/Transition', 'Transition'),
          page('angular', 'classes/Trace', 'Trace'),
        ]),
      ],
    },
    {
      type: 'category',
      label: '@uirouter/angular-hybrid',
      link: { type: 'doc', id: 'api/angular-hybrid/index' },
      items: [{ type: 'autogenerated', dirName: 'api/angular-hybrid' }],
    },
  ],
};

export default sidebars;
